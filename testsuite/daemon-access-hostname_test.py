#!/usr/bin/env python3
"""Daemon coverage: hosts allow / hosts deny hostname tokens matched by
forward DNS (access.c match_hostname).

"reverse lookup" is off in every config below, so the daemon has no
reverse-DNS name for the peer ("UNDETERMINED") and the reverse-name match
in match_hostname() can never fire: only the forward-lookup path -- resolve
the config's hostname token and compare the result against the peer's
numeric address -- can match.  The token is "localhost", which resolves to
the loopback address in both families, so the same token exercises the
IPv4 path against a 127.0.0.1 peer and the IPv6 path against a ::1 peer.

Also covered: "forward lookup = no" must disable the forward match, and a
token that fails to resolve must fail CLOSED in a deny list (the peer is
denied) while simply not matching in an allow list.

Like daemon-access-ip_test.py this needs a real TCP peer (--use-tcp), and
the configs set no global hosts allow so each module's own patterns are
the sole decider.  The IPv6 daemon is spawned directly (the shared
start_test_daemon helper binds 127.0.0.1 only) and its section is skipped
with a note when this host or build has no IPv6 loopback.
"""

import atexit
import socket
import subprocess
import time

from rsyncfns import (
    FROMDIR, RSYNC_PEER, SCRATCHDIR,
    claim_ports, make_tree, require_tcp, rmtree, rsync_argv,
    split_rsync_cmd, start_test_daemon, test_fail,
)

DAEMON_PORT = 12914
V6_PORT = 12917
UNRESOLVABLE = 'rsync-test-nonexistent.invalid'

require_tcp("hosts allow/deny forward-DNS matching needs a real TCP peer")

src = FROMDIR
rmtree(src)
make_tree(src, depth=2)


def resolves_to(name, family, addr):
    """True if `name` forward-resolves to the binary address `addr`."""
    try:
        infos = socket.getaddrinfo(name, None, family, socket.SOCK_STREAM)
    except socket.gaierror:
        return False
    return any(info[4][0] == addr for info in infos)


def write_conf(path, modules, log, pidfile):
    lines = [
        '# autogenerated by daemon-access-hostname_test.py',
        f'pid file = {pidfile}',
        'use chroot = no',
        # No reverse-DNS name for the peer: only forward matching can fire.
        'reverse lookup = no',
        f'log file = {log}',
        '',
    ]
    for mod, params in modules:
        lines.append(f'[{mod}]')
        lines.append(f'\tpath = {src}')
        lines.append('\tread only = yes')
        lines += [f'\t{k} = {v}' for k, v in params.items()]
        lines.append('')
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return path


def connect(url, mod):
    """Return rsync's exit code for listing the module over the daemon."""
    return subprocess.run(rsync_argv('-r', f'{url}{mod}/'),
                          stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
                          text=True).returncode


def allowed(url, mod, why):
    if connect(url, mod) != 0:
        test_fail(f"connection to {mod} should be ALLOWED ({why}) but was refused")


def denied(url, mod, why):
    if connect(url, mod) == 0:
        test_fail(f"connection to {mod} should be DENIED ({why}) but succeeded")


# --- IPv4 peer (127.0.0.1) -------------------------------------------------

if not resolves_to('localhost', socket.AF_INET, '127.0.0.1'):
    test_fail("this host does not resolve 'localhost' to 127.0.0.1; "
              "the forward-DNS cases cannot be constructed")

modules = [
    ('plain', {}),
    ('fwd-allow4', {'hosts allow': 'localhost'}),
    ('fwd-deny4', {'hosts deny': 'localhost'}),
    ('fwd-off', {'hosts allow': 'localhost', 'forward lookup': 'no'}),
]
# The unresolvable-token cases are only meaningful if the name really does
# not resolve here (a wildcard resolver would defeat them).
try:
    socket.getaddrinfo(UNRESOLVABLE, None, socket.AF_UNSPEC,
                       socket.SOCK_STREAM)
    print(f"note: {UNRESOLVABLE} unexpectedly resolves here; "
          "unresolvable-token cases skipped")
except socket.gaierror:
    modules += [
        ('deny-unresolvable', {'hosts deny': UNRESOLVABLE}),
        ('allow-unresolvable', {'hosts allow': UNRESOLVABLE}),
    ]

conf = write_conf(SCRATCHDIR / 'access-hostname.conf', modules,
                  SCRATCHDIR / 'rsyncd.log', SCRATCHDIR / 'rsyncd.pid')
url = start_test_daemon(conf, DAEMON_PORT)

allowed(url, 'plain', "no hosts patterns on the module")
allowed(url, 'fwd-allow4', "localhost forward-resolves to the 127.0.0.1 peer")
denied(url, 'fwd-deny4', "localhost forward-resolves to the 127.0.0.1 peer")
denied(url, 'fwd-off', "forward lookup is disabled for the module")
if any(mod == 'deny-unresolvable' for mod, _ in modules):
    denied(url, 'deny-unresolvable',
           "an unresolvable deny token fails closed")
    denied(url, 'allow-unresolvable',
           "an unresolvable allow token does not match")

# --- IPv6 peer (::1) --------------------------------------------------------

v6_ok = resolves_to('localhost', socket.AF_INET6, '::1')
if v6_ok:
    try:
        with socket.socket(socket.AF_INET6, socket.SOCK_STREAM) as s:
            s.bind(('::1', 0))
    except OSError:
        v6_ok = False

if not v6_ok:
    print("note: no IPv6 loopback for 'localhost' here; IPv6 cases skipped")
else:
    modules6 = [
        ('plain6', {}),
        ('fwd-allow6', {'hosts allow': 'localhost'}),
        ('fwd-deny6', {'hosts deny': 'localhost'}),
    ]
    conf6 = write_conf(SCRATCHDIR / 'access-hostname6.conf', modules6,
                       SCRATCHDIR / 'rsyncd6.log', SCRATCHDIR / 'rsyncd6.pid')
    claim_ports(V6_PORT)
    # start_test_daemon binds 127.0.0.1 only, so spawn the IPv6 daemon
    # directly, with the same flags start_rsyncd uses apart from --address.
    proc = subprocess.Popen(
        split_rsync_cmd(RSYNC_PEER) + [
            '--daemon', '--no-detach', '--address=::1',
            f'--port={V6_PORT}', f'--config={conf6}',
        ],
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL)
    atexit.register(proc.terminate)
    deadline = time.monotonic() + 10
    up = False
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            break
        try:
            with socket.create_connection(('::1', V6_PORT), timeout=0.5):
                up = True
                break
        except OSError:
            time.sleep(0.05)
    if not up:
        proc.terminate()
        print("note: rsyncd did not listen on ::1 (built without INET6?); "
              "IPv6 cases skipped")
    else:
        try:
            url6 = f'rsync://[::1]:{V6_PORT}/'
            allowed(url6, 'plain6', "no hosts patterns on the module")
            allowed(url6, 'fwd-allow6',
                    "localhost forward-resolves to the ::1 peer")
            denied(url6, 'fwd-deny6',
                   "localhost forward-resolves to the ::1 peer")
        finally:
            proc.terminate()
            proc.wait(timeout=5)

print("daemon-access-hostname: forward-DNS hosts allow/deny matching verified")
